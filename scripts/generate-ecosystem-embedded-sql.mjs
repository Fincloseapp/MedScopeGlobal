#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const files = [
  "supabase/migrations/20260825120000_mediflow_ecosystem.sql",
  "supabase/migrations/20260825220000_editorial_redakce.sql",
  "supabase/migrations/20260825230000_editorial_images.sql",
];
const parts = files.map((rel) => ({
  name: path.basename(rel),
  sql: fs.readFileSync(path.join(root, rel), "utf8"),
}));
const outPath = path.join(root, "lib/ecosystem/embedded-migrations.ts");
const out =
  "/** Auto-generated by scripts/generate-ecosystem-embedded-sql.mjs — do not edit. */\n" +
  "export const ECOSYSTEM_MIGRATION_SQL: { name: string; sql: string }[] = " +
  JSON.stringify(parts, null, 2) +
  ";\n";
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out);
console.log("wrote", outPath, "bytes=" + out.length);
