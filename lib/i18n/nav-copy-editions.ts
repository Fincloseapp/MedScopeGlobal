export type NavEditionNode = { label: string; description?: string };
export type NavEditionPack = Record<string, NavEditionNode>;

type Row = [label: string, description?: string];

function pack(rows: Record<string, Row>): NavEditionPack {
  const out: NavEditionPack = {};
  for (const [href, [label, description]] of Object.entries(rows)) {
    out[href] = description ? { label, description } : { label };
  }
  return out;
}

