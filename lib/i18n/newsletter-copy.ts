function copyKey(locale?: string | null): string {
  const raw = (locale ?? "en").trim();
  if (PACKS[raw]) return raw;
  try {
    const primary = primaryArticleLocale(normalizeLocale(raw));
    if (PACKS[primary]) return primary;
    if (primary === "zh") return "zh-CN";
  } catch {
    /* fall through */
  }
  if (raw.startsWith("zh")) return "zh-CN";
  if (raw.startsWith("en")) return "en";
  return "en";
}

export function newsletterCopyLocale(locale?: string | null): string {
  return copyKey(locale);
}

export function getNewsletterCopy(locale?: string | null): NewsletterCopy {
  return PACKS[copyKey(locale)] ?? PACKS.en;
}
