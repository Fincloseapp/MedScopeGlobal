export function formatPortal(template: string, vars: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => vars[key] ?? "");
}

export function getLocalizedDisclaimer(locale?: string | null): string {
  const key = pickCopyLocale(locale);
  if (key === "en") return MEDICAL_DISCLAIMER.en;
  return MEDICAL_DISCLAIMER[key as GlobalLocaleCode] ?? MEDICAL_DISCLAIMER.en;
}

